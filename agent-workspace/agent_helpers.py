# ─── Novelty Classification ────────────────────────────────────────────

NOVELTY_TYPES = {
    "novel": {
        "label": "Novel Contribution",
        "icon": "🆕",
        "color": "#22c55e",
        "description": "Truly new approach, algorithm, or design introduced by this project",
    },
    "existing": {
        "label": "Existing Work",
        "icon": "📚",
        "color": "#6b7280",
        "description": "Well-known technique, standard practice, or dependency from prior work",
    },
    "improved": {
        "label": "Improved from Prior Work",
        "icon": "✨",
        "color": "#f59e0b",
        "description": "Existing approach that has been significantly adapted, optimized, or extended",
    },
    "baseline": {
        "label": "Baseline / Common Practice",
        "icon": "🔧",
        "color": "#3b82f6",
        "description": "Industry standard, common pattern, or baseline implementation",
    },
}


def render_novelty_marker(novelty_type: str, fmt: str = "markdown") -> str:
    """Render a novelty marker in the specified output format.

    Args:
        novelty_type: One of "novel", "existing", "improved", "baseline"
        fmt: "markdown", "latex", or "html"

    Returns:
        Formatted marker string
    """
    info = NOVELTY_TYPES.get(novelty_type, NOVELTY_TYPES["existing"])
    label = info["label"]
    icon = info["icon"]
    color = info["color"]

    if fmt == "latex":
        r, g, b = _hex_to_rgb(color)
        return (
            f"\\textcolor[RGB]{{{r},{g},{b}}}{{\\textbf{{{icon} {label}}}}}"
        )
    elif fmt == "html":
        return (
            f'<span class="novelty-badge novelty-{novelty_type}" '
            f'style="background:{color}20;color:{color};'
            f'border:1px solid {color};border-radius:4px;'
            f'padding:2px 8px;font-size:0.85em;font-weight:600;">'
            f"{icon} {label}</span>"
        )
    else:
        return f"**{icon} {label}**"


def _hex_to_rgb(hex_color: str) -> tuple:
    hex_color = hex_color.lstrip("#")
    return tuple(int(hex_color[i : i + 2], 16) for i in (0, 2, 4))


