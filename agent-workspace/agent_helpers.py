def get_interactive_prompt(phase_key: str, **kwargs) -> str:
    """Get an interactive prompt for the specified phase.

    Args:
        phase_key: e.g. "phase0_intro", "phase1_complete"
        **kwargs: Format arguments for the prompt template

    Returns:
        Formatted prompt string
    """
    template = INTERACTIVE_PROMPTS.get(phase_key, "")
    return template.format(**kwargs) if template else ""


# ─── Config Helpers ────────────────────────────────────────────────────

DEFAULT_CONFIG = {
    "interactive": True,
    "novelty_highlight": True,
    "novelty_mode": "auto",
    "novelty_in_title": True,
    "novelty_in_toc": True,
}


def load_config(config_path: str) -> dict:
    """Load config.json and ensure interactive/novelty fields exist."""
    config = {}
    if os.path.exists(config_path):
        with open(config_path, "r") as f:
            config = json.load(f)
    for key, val in DEFAULT_CONFIG.items():
        config.setdefault(key, val)
    return config


def has_novelty_classification(findings_path: str) -> bool:
    """Check if research-findings.json has novelty classifications."""
    if not os.path.exists(findings_path):
        return False
    with open(findings_path, "r") as f:
        findings = json.load(f)
    for entry in findings.get("key_contributions", []):
        if "novelty" in entry:
            return True
    for entry in findings.get("architectural_decisions", []):
        if "novelty" in entry:
            return True
    return False


# ─── Research Summary Generation ───────────────────────────────────────

def generate_research_summary(findings: dict) -> str:
    """Generate a concise summary of research findings for Phase 2 review."""
    lines = []
    base_models = findings.get("base_models", [])
    patterns = findings.get("existing_patterns", [])
    zones = findings.get("potential_novelty_zones", [])

    lines.append(f"**Base models found:** {len(base_models)}")
    for m in base_models:
        lines.append(f"  - {m.get('name', '?')} ({m.get('type', '?')}) — {m.get('modification_level', '?')}")
    lines.append(f"**Known patterns:** {len(patterns)}")
    for p in patterns[:3]:
        lines.append(f"  - {p.get('pattern', '?')}")
    lines.append(f"**Potential novelty zones:** {len(zones)}")
    for z in zones[:3]:
        lines.append(f"  - {z.get('area', '?')}: {z.get('reason', '?')[:80]}")

    return "\n".join(lines)


# ─── Novelty Summary Generation ────────────────────────────────────────

def generate_novelty_summary(findings: dict) -> str:
    """Generate a summary table of novelty classifications."""
    lines = ["| Classification | Count |", "|----------------|-------|"]

    counts = {"novel": 0, "existing": 0, "improved": 0, "baseline": 0}

    for entry in findings.get("key_contributions", []):
        n = entry.get("novelty", "existing")
        if n in counts:
            counts[n] += 1
    for entry in findings.get("architectural_decisions", []):
        n = entry.get("novelty", "existing")
        if n in counts:
            counts[n] += 1

    for nt, count in counts.items():
        marker = render_novelty_marker(nt, fmt="markdown")
        lines.append(f"| {marker} | {count} |")

    return "\n".join(lines)
